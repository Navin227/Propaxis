import { PaymentRecord } from '@/src/types';

export function formatINR(amount: number): string {
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 0,
  }).format(amount);
}

export function formatINRCompact(amount: number): string {
  if (amount >= 10000000) {
    return `₹${(amount / 10000000).toFixed(2)} Cr`;
  }
  if (amount >= 100000) {
    return `₹${(amount / 100000).toFixed(2)} L`;
  }
  return formatINR(amount);
}

export function formatDate(dateStr: string): string {
  if (!dateStr) return '—';
  const date = new Date(dateStr);
  if (Number.isNaN(date.getTime())) return dateStr;
  return new Intl.DateTimeFormat('en-IN', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
  }).format(date);
}

export function formatDateTime(dateStr: string): string {
  if (!dateStr) return '—';
  const date = new Date(dateStr);
  if (Number.isNaN(date.getTime())) return dateStr;
  return new Intl.DateTimeFormat('en-IN', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  }).format(date);
}

export function formatRelativeTime(dateStr: string): string {
  const date = new Date(dateStr);
  if (Number.isNaN(date.getTime())) return dateStr;
  const diffMs = Date.now() - date.getTime();
  const diffMins = Math.floor(diffMs / 60000);
  if (diffMins < 1) return 'Just now';
  if (diffMins < 60) return `${diffMins}m ago`;
  const diffHours = Math.floor(diffMins / 60);
  if (diffHours < 24) return `${diffHours}h ago`;
  const diffDays = Math.floor(diffHours / 24);
  if (diffDays < 7) return `${diffDays}d ago`;
  return formatDate(dateStr);
}

export function downloadVerifiedReceipt(payment: PaymentRecord): void {
  if (!payment.verifiedByBackend || payment.status !== 'Paid') {
    throw new Error('Receipt can only be downloaded for backend-verified paid invoices.');
  }
  const receiptText = [
    '============================================================',
    '                    PROPAXIS RENT RECEIPT                   ',
    '           Verified Backend Payment Confirmation            ',
    '============================================================',
    `Invoice Number     : ${payment.invoiceNumber}`,
    `Billing Period     : ${payment.billingMonth}`,
    `Tenant Name        : ${payment.tenantName}`,
    `Property           : ${payment.propertyName}`,
    `Unit Number        : ${payment.unitNumber}`,
    `Amount Paid        : ${formatINR(payment.amount)}`,
    `Payment Method     : ${payment.method ?? 'Razorpay Gateway'}`,
    `Paid Timestamp     : ${formatDateTime(payment.paidDate ?? new Date().toISOString())}`,
    `Gateway Order ID   : ${payment.gatewayOrderId ?? 'N/A'}`,
    `Gateway Payment ID : ${payment.gatewayPaymentId ?? 'N/A'}`,
    `Verification State : VERIFIED_BY_SERVER`,
    '============================================================',
    'Generated by PropAxis Enterprise Property Operations Platform',
  ].join('\n');

  const blob = new Blob([receiptText], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = `Receipt_${payment.invoiceNumber}_${payment.unitNumber}.txt`;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(url);
}
